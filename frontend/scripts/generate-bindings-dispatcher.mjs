#!/usr/bin/env node
/**
 * Generate the Wails binding dispatcher (app.ts + app.js + app.d.ts) from the
 * wails-generated per-service binding files.
 *
 * Why this exists: the frontend imports every backend method from a single
 * ".../app" module. The wails generator only emits per-service modules
 * (queryservice.ts, ...) that import @wailsio/runtime at load time, which is
 * unsafe under Vitest/SSR. This dispatcher routes each method to its per-service
 * binding via a LAZY dynamic import, so:
 *   - one ".../app" import surface for the whole frontend,
 *   - test-safe (the runtime is only loaded when a binding is actually called),
 *   - reuses the validated per-service Call.ByID bindings (no name-format guessing),
 *   - fully derived from the Go services -> adding a Go method needs no hand-edit.
 *
 * Run after `wails3 generate bindings` (wired into build/Taskfile.yml's
 * generate:bindings:shim step). Output is deterministic (sorted).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const BINDINGS_DIR = join(HERE, '../bindings/github.com/jbeck018/howlerops')

/** file-base -> ServiceName, parsed from the generated index.js imports. */
function parseServiceFiles(indexSrc) {
  const files = []
  const re = /import \* as \w+ from "\.\/([\w-]+)\.js";/g
  let m
  while ((m = re.exec(indexSrc)) !== null) files.push(m[1])
  return files
}

function exportedFunctions(src) {
  const names = []
  const re = /^export function (\w+)\s*\(/gm
  let m
  while ((m = re.exec(src)) !== null) names.push(m[1])
  return names
}

function main() {
  const serviceFiles = parseServiceFiles(readFileSync(join(BINDINGS_DIR, 'index.js'), 'utf8')).sort()

  const methodToFile = {} // method -> service file base
  const collisions = []
  for (const fileBase of serviceFiles) {
    let src
    try {
      src = readFileSync(join(BINDINGS_DIR, `${fileBase}.js`), 'utf8')
    } catch {
      continue
    }
    for (const fn of exportedFunctions(src)) {
      if (methodToFile[fn] && methodToFile[fn] !== fileBase) {
        collisions.push(`${fn} (${methodToFile[fn]} + ${fileBase})`)
        continue // first service wins, matching the legacy dispatcher's order
      }
      methodToFile[fn] = fileBase
    }
  }
  if (collisions.length) {
    console.warn(`[dispatcher] method-name collisions (first wins): ${collisions.join(', ')}`)
  }

  const methods = Object.keys(methodToFile).sort()

  const loadersLiteral = serviceFiles
    .map((f) => `  '${f}': () => import('./${f}.js'),`)
    .join('\n')

  const methodMapLiteral = methods
    .map((m) => `  ${m}: '${methodToFile[m]}',`)
    .join('\n')

  const exportsLiteral = methods
    .map((m) => `export const ${m} = makeBinding('${m}')`)
    .join('\n')

  const appTs = `// Code generated by scripts/generate-bindings-dispatcher.mjs. DO NOT EDIT.
// Regenerate with \`make bindings\` (runs after \`wails3 generate bindings\`).
//
// Lazy dispatcher over the wails per-service bindings: gives the frontend one
// ".../app" import surface that is test-safe (each service module is imported
// lazily, only when a binding is first called, not at module load) and reuses the
// validated per-service Call.ByID bindings.

type BindingResult = any

// Loaders return the per-service module namespace; typed as any because this
// dispatcher routes calls dynamically by method name.
const loaders: Record<string, () => Promise<any>> = {
${loadersLiteral}
}

const methodService: Record<string, string> = {
${methodMapLiteral}
}

function makeBinding(method: string): (...args: unknown[]) => Promise<BindingResult> {
  return async (...args: unknown[]) => {
    const file = methodService[method]
    const load = loaders[file]
    if (!load) {
      throw new Error(\`Wails binding "\${method}" has no registered service module\`)
    }
    const mod = await load()
    const fn = mod[method]
    if (typeof fn !== 'function') {
      throw new Error(\`Wails binding "\${method}" not found in \${file}\`)
    }
    return fn(...args)
  }
}

${exportsLiteral}

export type JSONValue = string | number | boolean | null | JSONValue[] | { [key: string]: JSONValue }
export type JSONRecord = Record<string, JSONValue>
export type BindingObject = Record<string, unknown>
`

  const appJs = `// Code generated by scripts/generate-bindings-dispatcher.mjs. DO NOT EDIT.
// Keep legacy ".../app" imports on the runtime-safe dispatcher.
export * from "./app.ts";
`

  const appDts = `// Code generated by scripts/generate-bindings-dispatcher.mjs. DO NOT EDIT.
${serviceFiles.map((f) => `export * from './${f}'`).join('\n')}
`

  writeFileSync(join(BINDINGS_DIR, 'app.ts'), appTs)
  writeFileSync(join(BINDINGS_DIR, 'app.js'), appJs)
  writeFileSync(join(BINDINGS_DIR, 'app.d.ts'), appDts)

  console.log(
    `[dispatcher] generated app.ts (${methods.length} methods across ${serviceFiles.length} services)`
  )
}

main()
